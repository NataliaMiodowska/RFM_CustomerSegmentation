/* Standardising stock_code and casting customer_id to integer */
DROP VIEW IF EXISTS RETAIL_CLEAN_STAGE1 CASCADE;

CREATE VIEW RETAIL_CLEAN_STAGE1 AS
SELECT
	INVOICE_NO,
	UPPER(TRIM(STOCK_CODE)) AS STOCK_CODE,
	DESCRIPTION,
	QUANTITY,
	INVOICE_DATE,
	UNIT_PRICE,
	CUSTOMER_ID::NUMERIC::INTEGER AS CUSTOMER_ID,
	COUNTRY
FROM
	RETAIL_DATA;


/*
Filters applied:
- valid customer identifiers (exclude NULLs),
- positive unit prices,
- exclude negative quantities unless the invoice is marked as a cancellation (starts with 'C')
*/
DROP VIEW IF EXISTS RETAIL_CLEAN_STAGE2;

CREATE VIEW RETAIL_CLEAN_STAGE2 AS
SELECT
	*
FROM
	RETAIL_CLEAN_STAGE1
WHERE
	CUSTOMER_ID IS NOT NULL
	AND UNIT_PRICE > 0
	AND (
		QUANTITY >= 0
		OR INVOICE_NO LIKE 'C%'
	);


/* removing non-product stock_code like fees, adjustments, tests, gift etc */
DROP VIEW IF EXISTS RETAIL_CLEAN_STAGE3;

CREATE VIEW RETAIL_CLEAN_STAGE3 AS
SELECT
	*
FROM
	RETAIL_CLEAN_STAGE2
WHERE
	STOCK_CODE ~ '^[0-9]{5}[A-Z]{0,2}$';


/* removing duplicates */
DROP VIEW IF EXISTS RETAIL_CLEAN_STAGE4;

CREATE VIEW RETAIL_CLEAN_STAGE4 AS
SELECT DISTINCT
	*
FROM
	RETAIL_CLEAN_STAGE3;


/* excluding customers with cancellations only  */
DROP VIEW IF EXISTS RETAIL_CLEAN_STAGE5;

CREATE VIEW RETAIL_CLEAN_STAGE5 AS
SELECT
	*
FROM
	RETAIL_CLEAN_STAGE4
WHERE
	CUSTOMER_ID IN (
		SELECT
			CUSTOMER_ID
		FROM
			RETAIL_CLEAN_STAGE4
		WHERE
			INVOICE_NO NOT ILIKE 'C%'
	);

/* assigning most frequent description from regular sales to product name */
DROP VIEW IF EXISTS RETAIL_CLEAN_STAGE6;

CREATE VIEW RETAIL_CLEAN_STAGE6 AS
WITH RANKED_DESCRIPTIONS AS (
    SELECT
        STOCK_CODE,
        UPPER(REGEXP_REPLACE(TRIM(DESCRIPTION), '\s+', ' ', 'g')) AS CLEAN_DESCRIPTION,
        ROW_NUMBER() OVER (
            PARTITION BY STOCK_CODE
            ORDER BY COUNT(*) DESC, UPPER(REGEXP_REPLACE(TRIM(DESCRIPTION), '\s+', ' ', 'g'))
        ) AS RN
    FROM
        RETAIL_CLEAN_STAGE5
    WHERE
        DESCRIPTION IS NOT NULL
        AND QUANTITY > 0
        AND INVOICE_NO NOT ILIKE 'C%'
    GROUP BY
        STOCK_CODE,
        UPPER(REGEXP_REPLACE(TRIM(DESCRIPTION), '\s+', ' ', 'g'))
)
SELECT
    S5.INVOICE_NO,
    S5.STOCK_CODE,
    COALESCE(
        RD.CLEAN_DESCRIPTION,
        UPPER(REGEXP_REPLACE(TRIM(S5.DESCRIPTION), '\s+', ' ', 'g'))
    ) AS DESCRIPTION,
    S5.QUANTITY,
    S5.INVOICE_DATE,
    S5.UNIT_PRICE,
    S5.CUSTOMER_ID,
    S5.COUNTRY
FROM
    RETAIL_CLEAN_STAGE5 S5
LEFT JOIN
    RANKED_DESCRIPTIONS RD
    ON S5.STOCK_CODE = RD.STOCK_CODE
   AND RD.RN = 1;


/* mapping 'EIRE' to 'Ireland' and assigning the most recent invoice country for multi-country customers */
DROP VIEW IF EXISTS RETAIL_CLEAN_STAGE7;

CREATE VIEW RETAIL_CLEAN_STAGE7 AS
WITH LATEST_CUSTOMER_COUNTRY AS (
    SELECT DISTINCT ON (CUSTOMER_ID)
        CUSTOMER_ID,
        CASE
            WHEN COUNTRY = 'EIRE' THEN 'Ireland'
            ELSE COUNTRY
        END AS CLEAN_COUNTRY
    FROM
        RETAIL_CLEAN_STAGE6
    WHERE
        CUSTOMER_ID IS NOT NULL
    ORDER BY
        CUSTOMER_ID,
        INVOICE_DATE DESC,
        INVOICE_NO DESC
)
SELECT
    S6.INVOICE_NO,
    S6.STOCK_CODE,
    S6.DESCRIPTION,
    S6.QUANTITY,
    S6.INVOICE_DATE,
    S6.UNIT_PRICE,
    S6.CUSTOMER_ID,
    COALESCE(
        LCC.CLEAN_COUNTRY,
        CASE WHEN S6.COUNTRY = 'EIRE' THEN 'Ireland' ELSE S6.COUNTRY END
    ) AS COUNTRY
FROM
    RETAIL_CLEAN_STAGE6 S6
LEFT JOIN
    LATEST_CUSTOMER_COUNTRY LCC
    ON S6.CUSTOMER_ID = LCC.CUSTOMER_ID;


 /* assigning the later timestamp for invoices with multiple timestamps */
DROP VIEW IF EXISTS RETAIL_CLEAN_STAGE8;

CREATE VIEW RETAIL_CLEAN_STAGE8 AS
SELECT
    INVOICE_NO,
    STOCK_CODE,
    DESCRIPTION,
    QUANTITY,
    MAX(INVOICE_DATE) OVER (PARTITION BY INVOICE_NO) AS INVOICE_DATE,
    UNIT_PRICE,
    CUSTOMER_ID,
    COUNTRY
FROM
    RETAIL_CLEAN_STAGE7;


/* creating the final table with clean data */
DROP TABLE IF EXISTS RETAIL_CLEAN;

CREATE TABLE RETAIL_CLEAN AS
SELECT DISTINCT *
FROM RETAIL_CLEAN_STAGE8;


/* final check */
SELECT
    COUNT(*) AS NUMBER_OF_RECORDS,
    COUNT(DISTINCT INVOICE_NO) AS NUMBER_OF_INVOICES,
    COUNT(DISTINCT CUSTOMER_ID) AS NUMBER_OF_CUSTOMERS,
    COUNT(*) FILTER (WHERE DESCRIPTION IS NULL) AS NULL_DESCRIPTION,
    COUNT(*) FILTER (WHERE COUNTRY IS NULL) AS NULL_COUNTRY
FROM RETAIL_CLEAN;
