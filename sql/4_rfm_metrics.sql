/* Reference date - date of the last transaction +1 */
SELECT
	MAX(INVOICE_DATE::DATE) + 1
FROM
	RETAIL_CLEAN; -- 2011-12-10

DROP TABLE IF EXISTS RFM_METRICS;

CREATE TABLE RFM_METRICS AS
WITH
	RECENCY AS (
		SELECT
			CUSTOMER_ID,
			'2011-12-10' - MAX(INVOICE_DATE::DATE) AS DAYS_FROM_LAST_PURCHASE
		FROM
			RETAIL_CLEAN
		GROUP BY
			CUSTOMER_ID
	),
	FREQUENCY AS (
		SELECT
			CUSTOMER_ID,
			COUNT(DISTINCT INVOICE_NO) FILTER (
				WHERE
					INVOICE_NO NOT ILIKE 'c%'
			) AS NUMBER_OF_INVOICES
		FROM
			RETAIL_CLEAN
		GROUP BY
			CUSTOMER_ID
	),
	MONETARY AS (
		SELECT
			CUSTOMER_ID,
			SUM(QUANTITY * UNIT_PRICE) AS SUM_OF_MONEY_SPEND
		FROM
			RETAIL_CLEAN
		GROUP BY
			CUSTOMER_ID
	)
	
SELECT
	R.CUSTOMER_ID,
	R.DAYS_FROM_LAST_PURCHASE,
	F.NUMBER_OF_INVOICES,
	M.SUM_OF_MONEY_SPEND
FROM
	RECENCY R
	JOIN FREQUENCY F USING (CUSTOMER_ID)
	JOIN MONETARY M USING (CUSTOMER_ID)
WHERE
	M.SUM_OF_MONEY_SPEND > 0
ORDER BY
	CUSTOMER_ID;


/* Data quality testing */
SELECT
	CUSTOMER_ID,
	COUNT(*)
FROM
	RFM_METRICS
GROUP BY
	CUSTOMER_ID
HAVING
	COUNT(*) > 1;


SELECT
	COUNT(*) AS TOTAL_CUSTOMERS,
	COUNT(
		CASE
			WHEN DAYS_FROM_LAST_PURCHASE IS NULL
			OR DAYS_FROM_LAST_PURCHASE < 0 THEN 1
		END
	) AS INVALID_RECENCY,
	COUNT(
		CASE
			WHEN NUMBER_OF_INVOICES IS NULL
			OR NUMBER_OF_INVOICES < 1 THEN 1
		END
	) AS INVALID_FREQUENCY,
	COUNT(
		CASE
			WHEN SUM_OF_MONEY_SPEND IS NULL
			OR SUM_OF_MONEY_SPEND <= 0 THEN 1
		END
	) AS INVALID_MONETARY
FROM
	RFM_METRICS;


SELECT
	*
FROM
	RFM_METRICS
WHERE
	SUM_OF_MONEY_SPEND <= 0;


/* Sum check on the same customers (those excluded for Monetary <= 0 are not in rfm_metrics) */
SELECT
	'rfm_metrics' AS SOURCE,
	SUM(SUM_OF_MONEY_SPEND) AS TOTAL
FROM
	RFM_METRICS
UNION ALL
SELECT
	'retail_clean, customers in rfm_metrics',
	SUM(UNIT_PRICE * QUANTITY)
FROM
	RETAIL_CLEAN
WHERE
	CUSTOMER_ID IN (
		SELECT
			CUSTOMER_ID
		FROM
			RFM_METRICS
	);


