SELECT
	COUNT(DISTINCT CUSTOMER_ID)
FROM
	RETAIL_DATA;

/* CustomerID values that do not have the shape 12345.0 */
SELECT
	COUNT(*) AS NUMBER_OF_RECORDS
FROM
	RETAIL_DATA
WHERE
	CUSTOMER_ID IS NOT NULL
	AND CUSTOMER_ID !~ '^[0-9]{5}\.0$';

SELECT
	COUNT(*) FILTER (
		WHERE
			CUSTOMER_ID IS NULL
	) AS MISSING_ID_ROWS,
	ROUND(
		COUNT(*) FILTER (
			WHERE
				CUSTOMER_ID IS NULL
		) * 100.0 / COUNT(*),
		2
	) AS PCT_MISSING_ID_ROWS
FROM
	RETAIL_DATA;

SELECT
	*
FROM
	RETAIL_DATA
WHERE
	CUSTOMER_ID IS NULL
	AND (
		CHAR_LENGTH(STOCK_CODE) != 5
		OR CHAR_LENGTH(INVOICE_NO) != 6
	);


SELECT DISTINCT
	COUNTRY
FROM
	RETAIL_DATA;


/* customer activity: counts rows (invoice lines), not invoices */
WITH CUSTOMER_ACTIVITY AS (
    SELECT 
        CUSTOMER_ID,
        COUNT(*) FILTER (WHERE INVOICE_NO NOT ILIKE 'C%') AS PURCHASE_ROWS,
        COUNT(*) FILTER (WHERE INVOICE_NO ILIKE 'C%') AS CANCELLATION_ROWS
    FROM RETAIL_DATA
    WHERE CUSTOMER_ID IS NOT NULL
    GROUP BY CUSTOMER_ID
),
CUSTOMER_SEGMENTS AS (
    SELECT 
        CUSTOMER_ID,
        CASE 
            WHEN PURCHASE_ROWS > 0 AND CANCELLATION_ROWS > 0 THEN 'BOTH PURCHASES AND CANCELLATIONS'
            WHEN PURCHASE_ROWS > 0 AND CANCELLATION_ROWS = 0 THEN 'REGULAR PURCHASES ONLY'
            WHEN PURCHASE_ROWS = 0 AND CANCELLATION_ROWS > 0 THEN 'CANCELLATIONS ONLY'
        END AS ACTIVITY_TYPE
    FROM CUSTOMER_ACTIVITY
)
SELECT 
    ACTIVITY_TYPE,
    COUNT(*) AS CUSTOMER_COUNT,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 2) AS PCT_CUSTOMERS
FROM CUSTOMER_SEGMENTS
GROUP BY ACTIVITY_TYPE
ORDER BY CUSTOMER_COUNT DESC;
