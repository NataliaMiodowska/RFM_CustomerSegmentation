
/* data quality check */

SELECT
	COUNT(*)
FROM
	RETAIL_DATA;


SELECT
	COUNT(*) - COUNT(INVOICE_NO) AS NULL_INVOICE_NO,
	COUNT(*) - COUNT(STOCK_CODE) AS NULL_STOCK_CODE,
	COUNT(*) - COUNT(DESCRIPTION) AS NULL_DESCRIPTION,
	COUNT(*) - COUNT(QUANTITY) AS NULL_QUANTITY,
	COUNT(*) - COUNT(INVOICE_DATE) AS NULL_INVOICE_DATE,
	COUNT(*) - COUNT(UNIT_PRICE) AS NULL_UNIT_PRICE,
	COUNT(*) - COUNT(CUSTOMER_ID) AS NULL_CUSTOMER_ID,
	COUNT(*) - COUNT(COUNTRY) AS NULL_COUNTRY
FROM
	RETAIL_DATA;


SELECT
	*,
	COUNT(*) AS NUMBER_OF_DUPLICATES
FROM
	RETAIL_DATA
GROUP BY
	INVOICE_NO,
	STOCK_CODE,
	DESCRIPTION,
	QUANTITY,
	INVOICE_DATE,
	UNIT_PRICE,
	CUSTOMER_ID,
	COUNTRY
HAVING
	COUNT(*) > 1
ORDER BY
	NUMBER_OF_DUPLICATES DESC;
	
SELECT
	COUNT(DISTINCT INVOICE_NO)
FROM
	RETAIL_DATA;

SELECT
	CHAR_LENGTH(INVOICE_NO) AS LENGTH_INVOICE_NO
FROM
	RETAIL_DATA
GROUP BY
	CHAR_LENGTH(INVOICE_NO)
ORDER BY
	LENGTH_INVOICE_NO DESC;

SELECT
	INVOICE_NO,
	CHAR_LENGTH(INVOICE_NO) AS LENGTH_INVOICE_NO
FROM
	RETAIL_DATA
WHERE
	CHAR_LENGTH(INVOICE_NO) != 6
	AND LOWER(LEFT(INVOICE_NO, 1)) != 'c';



SELECT
	CHAR_LENGTH(STOCK_CODE) AS LENGTH_STOCK_CODE
FROM
	RETAIL_DATA
GROUP BY
	CHAR_LENGTH(STOCK_CODE)
ORDER BY
	LENGTH_STOCK_CODE DESC;

SELECT
	STOCK_CODE,
	COUNT(*) AS NUMBER_OF_RECORDS,
	SUM(QUANTITY * UNIT_PRICE) AS TOTAL_VALUE
FROM
	RETAIL_DATA
WHERE
	CHAR_LENGTH(STOCK_CODE) != 5
GROUP BY
	STOCK_CODE
ORDER BY
	TOTAL_VALUE DESC;

SELECT
	DESCRIPTION,
	COUNT(*) AS NUMBER_OF_RECORDS
FROM
	RETAIL_DATA
GROUP BY
	DESCRIPTION
ORDER BY 
	NUMBER_OF_RECORDS DESC;

SELECT
	STOCK_CODE,
	COUNT(DISTINCT DESCRIPTION) AS UNIQUE_DESCRIPTION_COUNT,
	ARRAY_AGG(DISTINCT DESCRIPTION) AS DESCRIPTION_VARIANTS
FROM
	RETAIL_DATA
WHERE
	DESCRIPTION IS NOT NULL
GROUP BY
	STOCK_CODE
HAVING
	COUNT(DISTINCT DESCRIPTION) > 1
ORDER BY
	UNIQUE_DESCRIPTION_COUNT DESC;

/* product name = most frequent description among regular sales */
SELECT DISTINCT
	ON (UPPER(TRIM(STOCK_CODE))) UPPER(TRIM(STOCK_CODE)) AS STOCK_CODE,
	DESCRIPTION AS PRODUCT_NAME,
	COUNT(*) AS NUMBER_OF_RECORDS
FROM
	RETAIL_DATA
WHERE
	DESCRIPTION IS NOT NULL
	AND QUANTITY > 0
	AND UNIT_PRICE > 0
	AND INVOICE_NO NOT ILIKE 'C%'
GROUP BY
	UPPER(TRIM(STOCK_CODE)),
	DESCRIPTION
ORDER BY
	UPPER(TRIM(STOCK_CODE)),
	NUMBER_OF_RECORDS DESC;

SELECT
	MIN(QUANTITY),
	MAX(QUANTITY)
FROM
	RETAIL_DATA;

SELECT
	COUNT(*)
FROM
	RETAIL_DATA
WHERE
	QUANTITY < 0
	AND LOWER(LEFT(INVOICE_NO, 1)) != 'c';

	

SELECT
	COUNT(DISTINCT INVOICE_NO) AS NUMBER_OF_INVOICES,
	DESCRIPTION
FROM
	RETAIL_DATA
WHERE
	QUANTITY < 0
	AND LOWER(LEFT(INVOICE_NO, 1)) != 'c'
GROUP BY
	DESCRIPTION
ORDER BY
	NUMBER_OF_INVOICES DESC;

SELECT
	COUNT(DISTINCT INVOICE_NO) AS NUMBER_OF_INVOICES,
	UNIT_PRICE
FROM
	RETAIL_DATA
WHERE
	QUANTITY < 0
	AND LOWER(LEFT(INVOICE_NO, 1)) != 'c'
	AND UNIT_PRICE = 0
GROUP BY
	UNIT_PRICE
ORDER BY
	NUMBER_OF_INVOICES DESC;


