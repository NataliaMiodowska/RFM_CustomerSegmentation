
/* data quality check */

SELECT
	COUNT(*)
FROM
	RETAIL_DATA;


SELECT
	COUNT(*) - COUNT(INVOICE_NO) AS NULL_INVOICE_NO,
	COUNT(*) - COUNT(STOCK_CODE) AS NULL_STOCK_CODE,
	COUNT(*) - COUNT(DESCRIPTION) AS NULL_DESCRIPTION,
	COUNT(*) - COUNT(QUANTITY) AS NULL_QUANTITY,
	COUNT(*) - COUNT(INVOICE_DATE) AS NULL_INVOICE_DATE,
	COUNT(*) - COUNT(UNIT_PRICE) AS NULL_UNIT_PRICE,
	COUNT(*) - COUNT(CUSTOMER_ID) AS NULL_CUSTOMER_ID,
	COUNT(*) - COUNT(COUNTRY) AS NULL_COUNTRY
FROM
	RETAIL_DATA;



SELECT
	*,
	COUNT(*) AS number_of_records
FROM
	RETAIL_DATA
GROUP BY
	INVOICE_NO,
	STOCK_CODE,
	DESCRIPTION,
	QUANTITY,
	INVOICE_DATE,
	UNIT_PRICE,
	CUSTOMER_ID,
	COUNTRY
HAVING
	COUNT(*) > 1
ORDER BY
	number_of_records DESC;



SELECT
	CHAR_LENGTH(INVOICE_NO) AS LENGTH_INVOICE_NO
FROM
	RETAIL_DATA
GROUP BY
	CHAR_LENGTH(INVOICE_NO)
ORDER BY
	LENGTH_INVOICE_NO DESC;

SELECT
	INVOICE_NO,
	CHAR_LENGTH(INVOICE_NO) AS LENGTH_INVOICE_NO
FROM
	RETAIL_DATA
WHERE
	CHAR_LENGTH(INVOICE_NO) != 6
	AND LOWER(LEFT(INVOICE_NO, 1)) != 'c';



SELECT
	CHAR_LENGTH(STOCK_CODE) AS LENGTH_STOCK_CODE
FROM
	RETAIL_DATA
GROUP BY
	CHAR_LENGTH(STOCK_CODE)
ORDER BY
	LENGTH_STOCK_CODE DESC;

SELECT
	STOCK_CODE,
	CHAR_LENGTH(STOCK_CODE) AS LENGTH_STOCK_CODE
FROM
	RETAIL_DATA
WHERE
	CHAR_LENGTH(STOCK_CODE) != 5
GROUP BY
	STOCK_CODE
ORDER BY
	LENGTH_STOCK_CODE DESC;


SELECT
	DESCRIPTION,
	COUNT(*) AS NUMBER_OF_EVENTS
FROM
	RETAIL_DATA
GROUP BY
	DESCRIPTION
ORDER BY 
	NUMBER_OF_EVENTS DESC;


SELECT
	COUNT(*)
FROM
	RETAIL_DATA
WHERE
	QUANTITY < 0
	AND LOWER(LEFT(INVOICE_NO, 1)) != 'c';

SELECT
	COUNT(DISTINCT INVOICE_NO) AS NUMBER_OF_EVENTS,
	DESCRIPTION
FROM
	RETAIL_DATA
WHERE
	QUANTITY < 0
	AND LOWER(LEFT(INVOICE_NO, 1)) != 'c'
GROUP BY
	DESCRIPTION
ORDER BY
	NUMBER_OF_EVENTS DESC;


SELECT
	EXTRACT(
		YEAR
		FROM
			INVOICE_DATE
	) AS YEAR
FROM
	RETAIL_DATA
GROUP BY
	YEAR;


SELECT
	UNIT_PRICE,
	COUNT(*) AS NUMMBER_OF_RECORDS
FROM
	RETAIL_DATA
WHERE
	UNIT_PRICE <= 0
GROUP BY
	UNIT_PRICE;

SELECT
	*
FROM
	RETAIL_DATA
WHERE
	UNIT_PRICE <= 0
ORDER BY
	UNIT_PRICE;

