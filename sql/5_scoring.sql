DROP TABLE IF EXISTS SCORING;

CREATE TABLE SCORING AS
WITH
	RECENCY_SCORING AS (
		SELECT
			CUSTOMER_ID,
			RECENCY,
			NTILE(5) OVER (
				ORDER BY
					RECENCY, CUSTOMER_ID
			) AS RECENCY_SCORE
		FROM
			RFM_METRICS
	),
	FREQUENCY_SCORING AS (
		SELECT
			CUSTOMER_ID,
			FREQUENCY,
			NTILE(5) OVER (
				ORDER BY
					FREQUENCY DESC, CUSTOMER_ID
			) AS FREQUENCY_SCORE
		FROM
			RFM_METRICS
	),
	MONETARY_SCORING AS (
		SELECT
			CUSTOMER_ID,
			MONETARY,
			NTILE(5) OVER (
				ORDER BY
					MONETARY DESC, CUSTOMER_ID
			) AS MONETARY_SCORE
		FROM
			RFM_METRICS
	)
SELECT
	RS.*,
	FREQUENCY,
	FREQUENCY_SCORE,
	MONETARY,
	MONETARY_SCORE
FROM
	RECENCY_SCORING RS
	JOIN FREQUENCY_SCORING FS USING (CUSTOMER_ID)
	JOIN MONETARY_SCORING MS USING (CUSTOMER_ID)
ORDER BY RECENCY,FREQUENCY DESC, MONETARY DESC;


/* Checking whether the groups size is the same */
WITH
	DISTRIBUTION_RECENCY AS (
		SELECT
			RECENCY_SCORE,
			COUNT(*) AS NUMBER_OF_RECORDS_RECENCY,
			ROUND(
				(
					COUNT(*)::NUMERIC / (
						SELECT
							COUNT(*)
						FROM
							SCORING
					)
				) * 100,
				2
			) AS PCT_OF_RECORDS_RECENCY
		FROM
			SCORING
		GROUP BY
			RECENCY_SCORE
	),
	DISTRIBUTION_FREQUENCY AS (
		SELECT
			FREQUENCY_SCORE,
			COUNT(*) AS NUMBER_OF_RECORDS_FREQUENCY,
			ROUND(
				(
					COUNT(*)::NUMERIC / (
						SELECT
							COUNT(*)
						FROM
							SCORING
					)
				) * 100,
				2
			) AS PCT_OF_RECORDS_FREQUENCY
		FROM
			SCORING
		GROUP BY
			FREQUENCY_SCORE
	),
	DISTRIBUTION_MONETARY AS (
		SELECT
			MONETARY_SCORE,
			COUNT(*) AS NUMBER_OF_RECORDS_MONETARY,
			ROUND(
				(
					COUNT(*)::NUMERIC / (
						SELECT
							COUNT(*)
						FROM
							SCORING
					)
				) * 100,
				2
			) AS PCT_OF_RECORDS_MONETARY
		FROM
			SCORING
		GROUP BY
			MONETARY_SCORE
	)
SELECT
	RECENCY_SCORE AS SCORE,
	NUMBER_OF_RECORDS_RECENCY,
	PCT_OF_RECORDS_RECENCY,
	NUMBER_OF_RECORDS_FREQUENCY,
	PCT_OF_RECORDS_FREQUENCY,
	NUMBER_OF_RECORDS_MONETARY,
	PCT_OF_RECORDS_MONETARY
FROM
	DISTRIBUTION_RECENCY
	JOIN DISTRIBUTION_FREQUENCY ON RECENCY_SCORE = FREQUENCY_SCORE
	JOIN DISTRIBUTION_MONETARY ON FREQUENCY_SCORE = MONETARY_SCORE